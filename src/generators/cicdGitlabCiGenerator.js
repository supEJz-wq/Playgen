export function generateCicdGitlabCi(model) {
  const p = model.pipeline
  const fw = p.automationFramework
  const lang = p.language
  const os = p.operatingSystem.toLowerCase()
  const reports = p.reports
  const artifacts = p.artifacts
  const trigger = p.trigger

  const image = fw === 'playwright'
    ? 'mcr.microsoft.com/playwright:v1.51.0-focal'
    : os === 'macos' ? 'macos:latest' : 'ubuntu:latest'

  const beforeScript = fw === 'playwright'
    ? 'before_script:\n  - npm ci\n  - npx playwright install --with-deps\n'
    : fw === 'selenium'
    ? seleniumBeforeScript(lang)
    : appiumBeforeScript(lang, p.platform)

  const testScript = fw === 'playwright'
    ? `    - npx playwright test${p.executionMode === 'headed' ? ' --headed' : ''}${reports.html ? '' : ' --reporter=list'}`
    : fw === 'selenium'
    ? seleniumTestScript(lang)
    : appiumTestScript(lang)

  const artifactPaths = []
  if (artifacts.reports) artifactPaths.push('reports/')
  if (artifacts.screenshots) artifactPaths.push('screenshots/')
  if (artifacts.videos) artifactPaths.push('videos/')
  if (artifacts.logs) artifactPaths.push('logs/')

  const artifactSection = artifactPaths.length > 0
    ? `\n  artifacts:\n    when: always\n    paths:\n      - ${artifactPaths.join('\n      - ')}\n    expire_in: 7 days`
    : ''

  const reportSection = generateGitlabReports(reports)

  const stages = fw === 'playwright'
    ? ['test']
    : ['install', 'test']

  const workflowName = p.pipelineName || `${fwLabel(fw)} CI/CD Pipeline`

  let content = `# ${workflowName}
# Generated by PlayGen CI/CD Generator
# Automation Framework: ${fwLabel(fw)} | Language: ${lang}
# https://playgen.app

stages:
${stages.map(s => `  - ${s}`).join('\n')}

variables:
  CI: "true"

${fw === 'playwright' ? '' : ''}${fwLabel(fw)}-Tests:
  stage: test
  image: ${image}
${beforeScript ? `  ${beforeScript}` : ''}  script:
${testScript}
${reportSection}${artifactSection}
`

  if (trigger === 'Scheduled Run') {
    content = `include:
  - template: Auto-DevOps.gitlab-ci.yml

` + content
  }

  return [
    { name: '.gitlab-ci.yml', content: content.trimStart() },
  ]
}

function fwLabel(fw) {
  return { playwright: 'Playwright', selenium: 'Selenium', appium: 'Appium' }[fw] || fw
}

function seleniumBeforeScript(lang) {
  switch (lang) {
    case 'Java':
      return `before_script:
  - apt-get update && apt-get install -y maven
  - mvn clean install -DskipTests
`
    case 'Python':
      return `before_script:
  - pip install -r requirements.txt
`
    case 'JavaScript':
      return `before_script:
  - npm ci
`
    case 'C#':
      return `before_script:
  - dotnet restore
`
    default:
      return `before_script:
  - npm ci
`
  }
}

function seleniumTestScript(lang) {
  switch (lang) {
    case 'Java': return '    - mvn test'
    case 'Python': return '    - pytest -v'
    case 'JavaScript': return '    - npx mocha --timeout 30000'
    case 'C#': return '    - dotnet test'
    default: return '    - mvn test'
  }
}

function appiumBeforeScript(lang, platform) {
  const driver = platform === 'iOS' ? 'xcuitest' : 'uiautomator2'
  const langScript = lang === 'Java'
    ? `  - apt-get update && apt-get install -y maven
  - mvn clean install -DskipTests`
    : lang === 'Python'
    ? `  - pip install -r requirements.txt`
    : lang === 'JavaScript'
    ? `  - npm ci`
    : `  - dotnet restore`

  return `before_script:
  - npm install -g appium
  - appium driver install ${driver}
  - appium &
  - sleep 5
${langScript}
`
}

function appiumTestScript(lang) {
  switch (lang) {
    case 'Java': return '    - mvn test'
    case 'Python': return '    - pytest -v'
    case 'JavaScript': return '    - npx wdio'
    case 'C#': return '    - dotnet test'
    default: return '    - mvn test'
  }
}

function generateGitlabReports(reports) {
  if (reports.junit) {
    return `\n  reports:\n    junit:\n      - test-results/**/*.xml`
  }
  return ''
}

